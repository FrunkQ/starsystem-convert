// BUILD THE MODULE OTHER SITES LOAD: static/module/v1/{convert.js, convert.d.ts, manifest.json}.
//
// Runs before the site build (`npm run build`), so the site serves the module it was built with. The
// manifest carries the release and each file's sha256: a caller that bundles a copy records those,
// so an import made years later can still say which converter made it.
import { execSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import fs from 'node:fs';

const OUT = 'static/module/v1';
const TYPES = '.svelte-kit/module-types/module';
const run = (cmd) => execSync(cmd, { stdio: 'inherit' });

run('npx svelte-kit sync');
run('npx vite build -c vite.module.config.ts --logLevel warn');
fs.rmSync('.svelte-kit/module-types', { recursive: true, force: true });
run('npx tsc -p tsconfig.module.json');

// One declaration file: the API types, then the functions, with the relative import between them
// dropped because they now sit in the same file.
const api = fs.readFileSync(`${TYPES}/api.d.ts`, 'utf8');
const index = fs
  .readFileSync(`${TYPES}/index.d.ts`, 'utf8')
  .replace(/^import [^;]*from '\.\/api';\n/m, '')
  .replace(/^export \* from '\.\/api';\n/m, '');
fs.writeFileSync(`${OUT}/convert.d.ts`, `// starsystem-convert module, API v1. Generated by scripts/build-module.mjs.\n${api}\n${index}`);

const pkg = JSON.parse(fs.readFileSync('package.json', 'utf8'));
const sha256 = (f) => createHash('sha256').update(fs.readFileSync(`${OUT}/${f}`)).digest('hex');
const files = Object.fromEntries(['convert.js', 'convert.d.ts'].map((f) => [f, { sha256: sha256(f), bytes: fs.statSync(`${OUT}/${f}`).size }]));
const manifest = { name: 'starsystem-convert', version: pkg.version, api: 1, files };
fs.writeFileSync(`${OUT}/manifest.json`, JSON.stringify(manifest, null, 2) + '\n');
console.log(`module ${pkg.version}: convert.js ${files['convert.js'].bytes} bytes, sha256 ${files['convert.js'].sha256.slice(0, 12)}…`);
