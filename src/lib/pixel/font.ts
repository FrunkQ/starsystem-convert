export const GLYPHS = G;
export const GLYPH_H = 7;

/** Fold a string onto the alphabet: capitals, accents stripped, anything unknown becomes a space. */
export function fold(text: string): string {
  return text
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toUpperCase()
    .replace(/[‘’]/g, "'")
    .replace(/[“”"]/g, '')
    .replace(/[–—]/g, '-')
    .split('')
    .map((ch) => (G[ch] ? ch : ' '))
    .join('')
    .replace(/ {2,}/g, ' ')
    .trim();
}
